export function format(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

interface I18n {
  lang: Lang;
  t: Dict;
  f: (key: keyof Dict, vars: Record<string, string | number>) => string;
  setLang: (l: Lang) => void;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('nmc.lang');
    if (saved === 'he' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  const nav = (navigator.languages?.[0] ?? navigator.language ?? 'he').toLowerCase();
  return nav.startsWith('en') ? 'en' : 'he';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
  }, [lang]);
  const value = useMemo<I18n>(
    () => ({
      lang,
      t: dicts[lang],
      f: (key, vars) => format(dicts[lang][key], vars),
      setLang: (l) => {
        try {
          localStorage.setItem('nmc.lang', l);
        } catch {
          /* ignore */
        }
        setLangState(l);
      },
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside provider');
  return v;
}
